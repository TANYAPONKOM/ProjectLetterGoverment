// ปรับปรุงฟังก์ชันทำย่อหน้าเนื้อหา ขอบขวาตรง และอักษรไม่ถ่างเกินไป
function addAcademicManualPara($section, array $lines, $spaceAfter = 80) {
    // เปลี่ยนจาก DISTRIBUTE เป็น BOTH (Justify ปกติ) เพื่อให้คำในบรรทัดสุดท้ายไม่โดนดึงยืด
    $run = $section->addTextRun([
        'alignment' => \PhpOffice\PhpWord\SimpleType\Jc::BOTH, 
        'lineHeight' => 1.15,
        'spaceBefore' => 0,
        'spaceAfter' => $spaceAfter,
        'indentation' => [
            'firstLine' => \PhpOffice\PhpWord\Shared\Converter::cmToTwip(2.5)
        ],
    ]);

    foreach ($lines as $index => $line) {
        $processedText = insertThaiWordBreaks(cleanWordText($line));
        $run->addText($processedText, 'normalFont');

        if ($index < count($lines) - 1) {
            $run->addTextBreak();
        }
    }
}

