// ฟังก์ชันสำหรับจัดย่อหน้าเนื้อหาให้อ่านง่าย ขอบขวาตรง และผูกกลุ่มคำไม่ให้วงเล็บตกหล่น
function addSpeakerManualPara($section, array $lines, $spaceAfter = 80) {
    $run = $section->addTextRun([
        'alignment' => \PhpOffice\PhpWord\SimpleType\Jc::BOTH, 
        'lineHeight' => 1.15,
        'spaceBefore' => 0,
        'spaceAfter' => $spaceAfter,
        'indentation' => [
            'firstLine' => \PhpOffice\PhpWord\Shared\Converter::cmToTwip(2.5)
        ],
    ]);

    foreach ($lines as $index => $line) {
        $cleanLine = cleanWordText($line);
        
        // ทางแก้ปัญหา วงเล็บ ): ผูกก้อนคำนี้ไว้ด้วยกัน ไม่ให้โปรแกรมดึงวงเล็บแยกไปบรรทัดใหม่
        if (strpos($cleanLine, '(รวมระยะเวลาในการเดินทาง)') !== false) {
            $parts = explode('(รวมระยะเวลาในการเดินทาง)', $cleanLine);
            
            // พิมพ์ข้อความส่วนแรก
            $run->addText(insertSpeakerThaiWordBreaks($parts[0]), 'normalFont');
            // พิมพ์กลุ่มคำในวงเล็บโดยล็อกห้ามแยกบรรทัดขาดออกจากกัน
            $run->addText('(รวมระยะเวลาในการเดินทาง)', 'normalFont');
            // พิมพ์ข้อความส่วนหลัง
            $run->addText(insertSpeakerThaiWordBreaks($parts[1]), 'normalFont');
        } else {
            $processedText = insertSpeakerThaiWordBreaks($cleanLine);
            $run->addText($processedText, 'normalFont');
        }

        if ($index < count($lines) - 1) {
            $run->addTextBreak();
        }
    }
}

